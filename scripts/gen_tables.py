#!/usr/bin/env python3
"""Generate src/tables.rs: HTML5 named entities and Unicode character classes.

Usage: python3 scripts/gen_tables.py > src/tables.rs

The data comes from the Python standard library (`html.entities` and
`unicodedata`), so the output depends on the Python version's Unicode data.
"""
import html.entities
import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for cp in range(0x80, sys.maxunicode + 1):
        if pred(chr(cp)):
            if start is None:
                start = cp
            end = cp
        elif start is not None:
            out.append((start, end))
            start = None
    if start is not None:
        out.append((start, end))
    return out


def emit_ranges(name, doc, rs):
    print(f"/// {doc}")
    print(f"pub(crate) static {name}: &[(u32, u32)] = &[")
    for a, b in rs:
        print(f"    (0x{a:04X}, 0x{b:04X}),")
    print("];")
    print()


print("// @generated by scripts/gen_tables.py. Do not edit by hand.")
print(f"// Unicode data version: {unicodedata.unidata_version}")
print()

emit_ranges(
    "PUNCTUATION",
    "Non-ASCII code points in the Unicode general categories P (punctuation) and S (symbol).",
    ranges(lambda c: unicodedata.category(c)[0] in "PS"),
)
emit_ranges(
    "WHITESPACE",
    "Non-ASCII code points in the Unicode general category Zs (space separator).",
    ranges(lambda c: unicodedata.category(c) == "Zs"),
)

emit_ranges(
    "SLUG",
    "Non-ASCII code points kept in heading ids: categories L, M, Nd and Nl.",
    ranges(lambda c: unicodedata.category(c)[0] in "LM" or unicodedata.category(c) in ("Nd", "Nl")),
)
emit_ranges(
    "MARK",
    "Non-ASCII code points in the Unicode general category M (mark).",
    ranges(lambda c: unicodedata.category(c)[0] == "M"),
)

entities = sorted(
    (k[:-1], v) for k, v in html.entities.html5.items() if k.endswith(";")
)
print("/// HTML5 named character references (without `&` and `;`), sorted by name.")
print("pub(crate) static ENTITIES: &[(&str, &str)] = &[")
for name, value in entities:
    escaped = "".join(
        c if c.isalnum() or c in " !#$%&()*+,-./:;<=>?@[]^_`{|}~" else f"\\u{{{ord(c):x}}}"
        for c in value
    )
    print(f'    ("{name}", "{escaped}"),')
print("];")
